const plural = ({ count, n }: { count: string; n: number | null }, one: string, many: string) => `${count} ${n === 1 ? one : many}`;

/** "Get the weather" reads after "to"; "Gets…" or "A tool that…" doesn't, so it is quoted instead. */
const imperative = (s: string) => !/^\P{L}*(a|an|the|this|that|it|tool|use|used|returns?)\b/iu.test(s) && !/^\P{L}*\p{L}*[^s\P{L}]s\b/u.test(s);
const toDo = (desc: string) => (imperative(desc) ? ` to ${lowerFirst(desc.replace(/\.\s*$/, ""))}` : `: ${desc}`);

const from = (source: string | null) => (source === null ? "" : ` from ${source}`);

const scopes: Record<Exclude<StepScope, null>, string> = { finalStep: "from the final step", allSteps: "from every step" };


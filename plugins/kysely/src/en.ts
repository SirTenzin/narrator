import type { KyselyPhrases } from "./phrases";

const caseNote = (ignoreCase: boolean) => (ignoreCase ? " (ignoring case)" : "");
const inParens = (items: string[]) => (items.length ? ` (${items.join(", ")})` : "");

export const en: KyselyPhrases = {
	compare: {
		equal: ({ left, right, neg }) => `${left} ${neg ? "is not" : "is"} ${right}`,
		moreThan: ({ left, right }) => `${left} is more than ${right}`,
		atLeast: ({ left, right }) => `${left} is at least ${right}`,
		lessThan: ({ left, right }) => `${left} is less than ${right}`,
		atMost: ({ left, right }) => `${left} is at most ${right}`,
		in: ({ left, right, neg }) => `${left} ${neg ? "is not in" : "is in"} ${right}`,
		between: ({ value, low, high, neg }) => `${value} ${neg ? "is not between" : "is between"} ${low} and ${high}`,
		empty: ({ value, neg }) => `${value} ${neg ? "is set" : "is empty"}`,
		other: ({ left, op, right, neg }) => (neg ? `it is not true that ${left} ${op} ${right}` : `${left} ${op} ${right}`),
	},
	pattern: {
		contains: ({ value, text, neg, ignoreCase }) => `${value} ${neg ? "does not contain" : "contains"} ${text}${caseNote(ignoreCase)}`,
		startsWith: ({ value, text, neg, ignoreCase }) => `${value} ${neg ? "does not start with" : "starts with"} ${text}${caseNote(ignoreCase)}`,
		endsWith: ({ value, text, neg, ignoreCase }) => `${value} ${neg ? "does not end with" : "ends with"} ${text}${caseNote(ignoreCase)}`,
		matches: ({ value, pattern, neg, ignoreCase }) => `${value} ${neg ? "does not match" : "matches"} the pattern ${pattern}${caseNote(ignoreCase)}`,
		regex: ({ value, pattern, neg, ignoreCase }) => `${value} ${neg ? "does not match" : "matches"} the regular expression ${pattern}${caseNote(ignoreCase)}`,
	},
	array: {
		containsAll: ({ value, items, neg }) => `${value} ${neg ? "does not contain all of" : "contains all of"} ${items}`,
		within: ({ value, items, neg }) => (neg ? `${value} has items outside ${items}` : `every item of ${value} is in ${items}`),
		overlaps: ({ value, items, neg }) => `${value} ${neg ? "shares nothing with" : "shares at least one item with"} ${items}`,
	},
	exists: {
		lookup: ({ query, neg }) => `${neg ? "nothing is found" : "something is found"} when we ${query}`,
	},
	logic: {
		all: "all of these are true:",
		any: "any of these is true:",
		allIn: ({ list, neg }) => (neg ? `some condition in ${list} fails` : `every condition in ${list} holds`),
		anyIn: ({ list, neg }) => (neg ? `no condition in ${list} holds` : `some condition in ${list} holds`),
	},
	order: {
		ascending: ({ column, time }) => `${column} (${time ? "oldest" : "lowest"} first)`,
		descending: ({ column, time }) => `${column} (${time ? "newest" : "highest"} first)`,
		nulls: ({ order, first }) => `${order}, empty values ${first ? "first" : "last"}`,
	},
	value: {
		column: ({ table, column }) => `${table}'s ${column}`,
		excluded: ({ column }) => `the new ${column}`,
		named: ({ value, name }) => `${value}, named ${name}`,
		allColumnsOf: ({ table }) => `every column of ${table}`,
		fn: ({ name, args }) => `the SQL function ${name} of ${args}`,
		cast: ({ value, type }) => `${value} as ${type}`,
		subquery: ({ query }) => `the result of: ${query}`,
		caseOf: "depending on the row:",
		when: ({ condition, value }) => `when ${condition}: ${value}`,
		otherwise: ({ value }) => `otherwise: ${value}`,
		jsonArray: ({ query }) => `a JSON list of the rows we get when we ${query}`,
		jsonObject: ({ query }) => `a JSON object of the row we get when we ${query}`,
	},
	aggregate: {
		countRows: "the number of rows",
		count: ({ column }) => `the number of rows with ${column} set`,
		countDistinct: ({ column }) => `the number of different ${column} values`,
		sum: ({ column }) => `the total of ${column}`,
		avg: ({ column }) => `the average of ${column}`,
		min: ({ column }) => `the smallest ${column}`,
		max: ({ column }) => `the largest ${column}`,
		coalesce: ({ values }) => `the first of ${values} that is set`,
	},
	query: {
		select: ({ fields, table }) => `look up ${fields} from ${table}`,
		fromRows: ({ table }) => `look up rows from ${table}`,
		fromFields: ({ table }) => `look up fields from ${table}`,
		picking: ({ fields }) => `picking ${fields}`,
		pickingBlock: "picking",
		tableDefinedAs: "where the table is",
		insertInto: ({ table }) => `insert into ${table}`,
		replaceInto: ({ table }) => `insert into ${table}, replacing rows that already exist`,
		update: ({ table }) => `update ${table}`,
		deleteFrom: ({ table }) => `delete from ${table}`,
		mergeInto: ({ table }) => `merge rows into ${table}`,
		values: ({ values }) => `the values: ${values}`,
		rows: "these rows:",
		row: "a row with",
		valuesFrom: ({ query }) => `the rows we get when we ${query}`,
		setting: ({ changes }) => `setting ${changes}`,
		where: ({ condition }) => `where ${condition}`,
		joined: ({ table, condition }) => `joined with ${table} on ${condition}`,
		leftJoined: ({ table, condition }) => `joined with ${table} where there is a match, on ${condition}`,
		rightJoined: ({ table, condition }) => `joined with every row of ${table}, matched where ${condition}`,
		fullJoined: ({ table, condition }) => `joined with ${table}, keeping unmatched rows on both sides, on ${condition}`,
		crossJoined: ({ table }) => `paired with every row of ${table}`,
		joinedOn: ({ table }) => `joined with ${table} where`,
		sortedBy: ({ columns }) => `sorted by ${columns}`,
		atMost: ({ count }) => `at most ${count} row(s)`,
		skipping: ({ count }) => `skipping the first ${count}`,
		groupedBy: ({ columns }) => `grouped by ${columns}`,
		having: ({ condition }) => `keeping only groups where ${condition}`,
		distinct: "without duplicate rows",
		distinctOn: ({ columns }) => `keeping only the first row for each ${columns}`,
		returning: ({ fields }) => `giving back ${fields}`,
		returningAll: "giving back the affected rows",
		ignoreConflicts: "ignoring rows that already exist",
		ignoreConflictsOn: ({ target }) => `ignoring rows that already exist (matched on ${target})`,
		updateConflicts: "updating rows that already exist",
		updateConflictsOn: ({ target }) => `updating rows that already exist (matched on ${target})`,
		constraint: ({ name }) => `the constraint ${name}`,
		locking: ({ mode }) => `locking rows (${mode})`,
		onlyIf: ({ condition }) => `only if ${condition}`,
		passedThrough: ({ fn }) => `passed through ${fn}`,
		cte: ({ name }) => `using the named subquery ${name}, defined as`,
		refined: ({ query }) => `${query} with these clauses added`,
		otherStep: ({ method, args }) => `then ${method}${args ? ` (${args})` : ""}`,
		whenMatched: "for rows that match",
		whenNotMatched: "for rows that don't match",
		using: ({ table, condition }) => `using ${table}, matched on ${condition}`,
		thenUpdate: "update them",
		thenDelete: "delete them",
		thenInsert: "insert them",
		thenDoNothing: "do nothing",
	},
	run: {
		first: ({ query }) => `the first row we get when we ${query}`,
		firstOrFail: ({ query }) => `the first row we get when we ${query}, failing if there is none`,
		results: ({ query }) => `the result of: ${query}`,
		stream: ({ query }) => `the rows, streamed as they arrive, when we ${query}`,
		compile: ({ query }) => `the SQL (not run) to ${query}`,
		explain: ({ query }) => `the database's plan to ${query}`,
		runQuery: ({ query }) => `run ${query}`,
	},
	transaction: {
		run: ({ settings }) => `do this all-or-nothing, in one transaction${inParens(settings)}:`,
		result: ({ settings }) => `the result of an all-or-nothing transaction${inParens(settings)} that does:`,
		isolation: ({ level }) => `isolation level ${level}`,
		accessMode: ({ mode }) => `${mode}`,
	},
};

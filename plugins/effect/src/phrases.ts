/** A phrase built from already-rendered strings. */
type P<K extends string> = (p: { [k in K]: string }) => string;
/** The same idea as a description ("an effect that waits 1 second") and as a step to do ("wait 1 second"). */
type Form<K extends string> = { noun: P<K>; act: P<K> };
/** A step that takes a callback: with a named parameter, with an unnamed one, or with a function reference. */
type Callback<K extends string> = { named: P<K | "name">; anon: P<K>; fn: P<Exclude<K, "value" | "action" | "cond"> | "fn"> };
/** A yes/no condition; `neg` asks for the negated reading. */
type Cond = (p: { subject: string; neg: boolean }) => string;


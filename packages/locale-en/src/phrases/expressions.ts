import type { ExpressionPhrases } from "@narrate/core";
import { grammar, possessiveChain } from "../grammar";

export const expressions: ExpressionPhrases = {
	ops: {
		"+": ({ left, right }) => `${left} plus ${right}`,
		"-": ({ left, right }) => `${left} minus ${right}`,
		"*": ({ left, right }) => `${left} times ${right}`,
		"/": ({ left, right }) => `${left} divided by ${right}`,
		"%": ({ left, right }) => `${left} modulo ${right}`,
		"**": ({ left, right }) => `${left} to the power of ${right}`,
		"<<": ({ left, right }) => `${left} shifted left by ${right}`,
		">>": ({ left, right }) => `${left} shifted right by ${right}`,
		"&": ({ left, right }) => `${left} bitwise-and ${right}`,
		"|": ({ left, right }) => `${left} bitwise-or ${right}`,
	},
	fallback: ({ value, fallback }) => `${value}, or ${fallback} if that's missing`,
	fallbackBlock: ({ value, fallback }) => `${value}, or if that's missing, ${fallback}`,
	fallbackInline: ({ value, fallback }) => `${value} (or ${fallback} if that's missing)`,
	orIfEmpty: ({ value, fallback }) => `${value}, or ${fallback} if that's empty`,
	onlyIf: ({ value, condition }) => `${value} (only if ${condition})`,
	folded: ({ value, expression }) => `${value} (${expression})`,
	concatText: ({ left, right }) => `${left} followed by ${right}`,
	nothing: "nothing",
	this: "this",
	parentClass: "the parent class",
	metaProperty: "this module's info",
	importMeta: {
		main: "this file is being run directly",
		dir: "this file's folder",
		url: "this file's URL",
		path: "this file's path",
	},
	envVar: ({ name }) => `the ${name} environment variable`,
	whether: ({ condition }) => `whether ${condition}`,
	allOf: ({ value }) => `all of ${value}`,
	everythingIn: ({ value }) => `everything in ${value}`,
	typeOf: ({ value }) => `the type of ${value}`,
	negative: ({ value }) => `negative ${value}`,
	asNumber: ({ value }) => `${value} as a number`,
	increment: ({ target }) => `increase ${target} by 1`,
	decrement: ({ target }) => `decrease ${target} by 1`,
	sequence: ({ steps }) => steps.join("; then "),
	yield: ({ value }) => `yield ${value}`,
	yieldAll: ({ value }) => `everything yielded by ${value}`,
	dynamicImport: ({ path }) => `the module at ${path}`,
	sql: ({ query }) => `the SQL ${query}`,
	classExpr: ({ name }) => `a class${name ? ` ${name}` : ""}`,
	labeled: ({ key, value }) => `${key}: ${value}`,
	item: "item",
	member: {
		countOf: ({ value }) => `the number of ${value}`,
		countWhere: ({ collection, condition }) => `the number of ${collection} where ${condition}`,
		countWhose: ({ collection, condition }) => `the number of ${collection} whose ${condition}`,
		firstOf: ({ value }) => `the first of ${value}`,
		lastOf: ({ value }) => `the last of ${value}`,
		nthOf: ({ value, position }) => `item #${position} of ${value}`,
		firstItem: ({ item }) => `first ${item}`,
		entryFor: ({ owner, key }) => `${grammar.possessive(owner)} entry for ${key}`,
		chain: ({ path }) => (path.length <= 4 ? possessiveChain(path) : `the ${path.at(-1)} of ${possessiveChain(path.slice(0, -1))}`),
		contextChain: ({ path }) => `the ${possessiveChain(path)}`,
		fromResult: ({ path, source }) => `the ${possessiveChain(path)} from ${source}`,
		context: "the context",
	},
	array: {
		empty: "an empty list",
		withoutDuplicates: ({ value }) => `${value} without duplicates`,
		copyOf: ({ value }) => `a copy of ${value}`,
		concat: ({ parts }) => parts.join(", plus "),
		concatBlock: "one list combining",
		listOf: ({ items }) => `a list of ${items}`,
		listOfBlock: "a list of",
	},
	object: {
		empty: "an empty object",
		override: ({ key, value }) => `${key} set to ${value}`,
		withOverrides: ({ base, overrides }) => `${base}, but with ${overrides}`,
		withOverridesBlock: ({ base }) => `${base}, but with`,
		getter: ({ key }) => `${key} (computed)`,
		method: ({ key, params }) => `${key}, a function${params ? ` of ${params}` : ""} that`,
		with: ({ items }) => `an object with ${items}`,
		withBlock: "an object with",
	},
	ternary: {
		nothingIf: ({ condition, otherwise }) => `nothing if ${condition}; otherwise ${otherwise}`,
		otherwiseNote: ({ value, condition, otherwise }) => `${value} if ${condition} (otherwise ${otherwise})`,
		onlyIfBlock: ({ value, condition }) => `(only if ${condition}) ${value}`,
		otherwiseNothing: ({ value, condition }) => `${value} if ${condition} (otherwise nothing)`,
		inline: ({ value, condition, otherwise }) => `${value} if ${condition}, otherwise ${otherwise}`,
		ifSo: ({ value }) => `if so: ${value}`,
		ifNot: ({ value }) => `if not: ${value}`,
		depending: ({ condition }) => `depending on whether ${condition}`,
	},
	assign: {
		callInto: ({ call, target }) => `${call}, and put the result in ${target}`,
		set: ({ target, value }) => `set ${target} to ${value}`,
		add: ({ target, value }) => `add ${value} to ${target}`,
		subtract: ({ target, value }) => `subtract ${value} from ${target}`,
		multiply: ({ target, value }) => `multiply ${target} by ${value}`,
		setIfMissing: ({ target, value }) => `if ${target} is missing, set it to ${value}`,
		setIfEmpty: ({ target, value }) => `if ${target} is empty, set it to ${value}`,
		replaceIfSet: ({ target, value }) => `if ${target} is set, replace it with ${value}`,
	},
	lambda: {
		params: ({ params }) => ` of ${params}`,
		giving: ({ params, value }) => `a function${params ? ` of ${params}` : ""} giving back ${value}`,
		steps: ({ params }) => `a function${params ? ` of ${params}` : ""} that`,
	},
	params: {
		typed: ({ name, type }) => `${name} ${type}`,
		withDefault: ({ name, value }) => `${name} (default ${value})`,
		rest: ({ name }) => `any other ${name}`,
		restOf: ({ name }) => `the rest as ${name}`,
		renamed: ({ key, local }) => `${key} (as ${local})`,
	},
	args: {
		inline: ({ list }) => ` (${list})`,
		flagOff: ({ key }) => `no ${key}`,
	},
	jsx: {
		fragment: "a group of",
		steps: "these steps",
		element: ({ tag, attrs }) => `${tag}${attrs.length ? ` (${attrs.join("; ")})` : ""}`,
		text: ({ text }) => `the text ${text}`,
		onlyIf: ({ condition, value }) => `only if ${condition}: ${value}`,
		showing: ({ element, child }) => `${element} showing ${child}`,
		containing: ({ element }) => `${element} containing`,
	},
	errors: {
		generic: "an error",
		label: ({ words }) => `${grammar.article(words)} ${words}`,
		describe: ({ label, message, code, status }) =>
			`${label}${message !== null ? `: ${message}` : ""}${code !== null ? ` [${code}]` : ""}${status !== null ? ` (status ${status})` : ""}`,
	},
};

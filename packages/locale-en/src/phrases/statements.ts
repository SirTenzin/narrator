import type { StatementPhrases } from "@narrate/core";

export const statements: StatementPhrases = {
	comment: ({ text }) => `“${text}”`,
	doNothing: "Do nothing",
	continue: "Move on to the next one",
	break: "Stop the loop",
	stop: "Stop here",
	exportDefault: ({ value }) => `export ${value} as the default`,
	loopForever: "Keep repeating (until something stops it)",
	whileBlock: "Keep repeating while all of this holds",
	while: ({ condition }) => `Keep repeating while ${condition}`,
	doOnce: "Do the following at least once",
	doWhileTail: ({ condition }) => `…and keep repeating while ${condition}`,
	loopItem: {
		each: ({ item }) => `each ${item}`,
		key: ({ key, value }) => `each key ${key}${value ? ` and value ${value}` : ""}`,
		indexed: ({ item, position }) => `each ${item}${position ? ` (at position ${position})` : ""}`,
	},
	forOf: ({ label, collection, async }) => `For ${label} in ${collection}${async ? " (as they arrive)" : ""}`,
	forIndex: ({ index, collection }) => `For each position ${index} in ${collection}`,
	countFrom: ({ index, start, condition }) => `Count ${index} from ${start} while ${condition}`,
	forParts: ({ init, test, update }) =>
		[init !== null && `start with ${init}`, test !== null && `repeat while ${test}`, update !== null && `then ${update} each time`].filter(Boolean).join(", "),
	ifThen: ({ condition, action }) => `If ${condition}, ${action}`,
	if: ({ condition }) => `If ${condition}`,
	ifBlock: "If all of this holds",
	then: "then",
	elseIf: ({ condition }) => `Otherwise, if ${condition}`,
	otherwise: "Otherwise",
	skipIf: ({ condition }) => `skip it if ${condition}`,
	breakIf: ({ condition }) => `stop the loop if ${condition}`,
	returnNothing: "Give back nothing",
	returnWhether: ({ condition }) => `Give back whether ${condition}`,
	returnCall: ({ call }) => `${call}, and give back the result`,
	returnEither: ({ value, condition, otherwise }) => `Give back ${value} if ${condition}, otherwise ${otherwise}`,
	return: ({ value }) => `Give back ${value}`,
	throw: ({ error }) => `Fail with ${error}`,
	try: "Try the following",
	catchIgnore: "If anything fails, ignore it",
	catch: ({ error }) => `If anything fails${error ? ` (call the problem ${error})` : ""}`,
	finally: "Either way, finally",
	switch: ({ value }) => `Depending on ${value}`,
	case: ({ values }) => `If it is ${values}`,
	caseOrDefault: ({ values }) => `If it is ${values}, or anything else`,
	default: "For anything else",
};

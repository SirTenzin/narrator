/** Why a file is skipped by default: it wasn't written by hand, so its English would be noise. */
export type SkipReason = "generated" | "vendored" | "build output" | "dependency" | "lockfile" | "minified";

const DIR_REASONS: Record<string, SkipReason> = {
	node_modules: "dependency",
	bower_components: "dependency",
	jspm_packages: "dependency",
	".yarn": "vendored",
	vendor: "vendored",
	dist: "build output",
	".next": "build output",
	".nuxt": "build output",
	".output": "build output",
	".svelte-kit": "build output",
	".vercel": "build output",
	".netlify": "build output",
	".turbo": "build output",
	".cache": "build output",
	coverage: "build output",
};

const FILE_REASONS: [RegExp, SkipReason][] = [
	[/(^|\/)(package-lock\.json|npm-shrinkwrap\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|deno\.lock)$/, "lockfile"],
	[/(^|\/)\.pnp\.(c?js|loader\.mjs)$/, "generated"],
	[/[.-]min\.[cm]?js$/, "minified"],
	[/\.(bundle|chunk)\.[cm]?js$/, "build output"],
];

// Tooling often lives in `build/` or `out/` as TypeScript; only compiled JavaScript there is build output.
const JS_OUTPUT_DIRS = new Set(["build", "out"]);
const JS_FILE = /\.[cm]?jsx?$/;

/** The skip reason a path alone gives away: build folders, dependency folders, lockfiles, `*.min.js`. Pass a project-relative path. */
export function pathSkipReason(path: string): SkipReason | null {
	const p = path.replaceAll("\\", "/");
	const isJs = JS_FILE.test(p);
	for (const segment of p.split("/").slice(0, -1)) {
		const reason = DIR_REASONS[segment] ?? (isJs && JS_OUTPUT_DIRS.has(segment) ? "build output" : undefined);
		if (reason) return reason;
	}
	return FILE_REASONS.find(([re]) => re.test(p))?.[1] ?? null;
}

// A banner comment in the first lines, like "// Code generated by X. DO NOT EDIT." or "/** @generated */".
const GENERATED_BANNER = /^\s*(?:\/\/|\/\*|\*).*(?:@generated\b|\bdo not edit\b|\bgenerated by\b)/im;
const SAMPLE = 64 * 1024;

/** Content checks that stay cheap on huge files: a generated-code banner, or minified code (long lines, few newlines). */
export function contentSkipReason(src: string): SkipReason | null {
	if (GENERATED_BANNER.test(src.split("\n", 5).join("\n"))) return "generated";
	if (src.length < 1024) return null;
	const sample = src.slice(0, SAMPLE);
	let lines = 1;
	let longest = 0;
	let start = 0;
	for (let i = sample.indexOf("\n"); i !== -1; i = sample.indexOf("\n", start)) {
		longest = Math.max(longest, i - start);
		start = i + 1;
		lines++;
	}
	longest = Math.max(longest, sample.length - start);
	return sample.length / lines > 160 || longest > 10_000 ? "minified" : null;
}

/** Why `path` should be skipped by default, or null when it reads like hand-written code. */
export function skipReason({ path, src }: { path: string; src?: string }): SkipReason | null {
	return pathSkipReason(path) ?? (src ? contentSkipReason(src) : null);
}

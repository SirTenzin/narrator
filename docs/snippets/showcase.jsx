export const Showcase = ({ examples }) => {
	const [active, setActive] = useState(0);
	const [hover, setHover] = useState(null);
	const ex = examples[active];

	const lineInRange = (n, l) => l && l.from !== null && n >= l.from && n <= l.to;
	const codeLit = (n) => hover && (hover.side === "code" ? hover.n === n : lineInRange(n, ex.english[hover.i]));
	const span = (l) => l.to - l.from;
	const narrowest = (n) => Math.min(...ex.english.filter((l) => lineInRange(n, l)).map(span));
	const englishLit = (i) =>
		hover && (hover.side === "english" ? hover.i === i : lineInRange(hover.n, ex.english[i]) && span(ex.english[i]) === narrowest(hover.n));

	const pick = (i) => {
		setActive(i);
		setHover(null);
	};

	return (
		<div className="nr-showcase not-prose">
			<div className="nr-showcase-bar">
				<div className="nr-tabs" role="tablist">
					{examples.map((e, i) => (
						<button key={e.id} role="tab" aria-selected={i === active} className={i === active ? "nr-tab nr-tab-on" : "nr-tab"} onClick={() => pick(i)}>
							{e.label}
						</button>
					))}
				</div>
				<span className="nr-file">{ex.file}</span>
			</div>
			<div className="nr-panes" onMouseLeave={() => setHover(null)}>
				<div>
					<div className="nr-pane-label">Code</div>
					<pre className="nr-code" aria-label="Source code">
						{ex.code.map((segs, i) => (
							<div key={i} className={codeLit(i + 1) ? "nr-cl nr-lit" : "nr-cl"} onMouseEnter={() => setHover({ side: "code", n: i + 1 })}>
								<span className="nr-ln">{i + 1}</span>
								<span>
									{segs.map(([k, t], j) => (
										<span key={j} className={k ? `nr-${k}` : undefined}>
											{t}
										</span>
									))}
									{segs.length === 0 ? " " : null}
								</span>
							</div>
						))}
					</pre>
				</div>
				<div className="nr-english" aria-label="Narration">
					<div className="nr-pane-label">English</div>
					{ex.english.map((l, i) =>
						l === null ? (
							<div key={i} className="nr-gap" />
						) : (
							<div
								key={i}
								className={`nr-el nr-${l.kind} nr-d${Math.min(l.d, 5)}${englishLit(i) ? " nr-lit" : ""}`}
								onMouseEnter={() => setHover({ side: "english", i })}
							>
								{l.s.map(([k, t], j) => (
									<span key={j} className={k ? `nr-m-${k}` : undefined}>
										{t}
									</span>
								))}
							</div>
						),
					)}
				</div>
			</div>
			<div className="nr-caption">Generated by Narrator from the code on the left. Hover a line to see where it came from.</div>
		</div>
	);
};
